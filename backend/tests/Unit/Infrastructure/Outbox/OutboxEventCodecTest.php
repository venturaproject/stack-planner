<?php

declare(strict_types=1);

namespace App\Tests\Unit\Infrastructure\Outbox;

use App\Domain\Product\Event\ProductCreated;
use App\Infrastructure\Outbox\OutboxEventCodec;
use DateTimeInterface;
use PHPUnit\Framework\TestCase;
use RuntimeException;

final class OutboxEventCodecTest extends TestCase
{
    public function testEncodesOnlyJsonDataAndCompletesAnAutoGeneratedAggregateId(): void
    {
        $codec = new OutboxEventCodec();
        $payload = $codec->encode(new ProductCreated(null, 'TSH-0001', 'T-Shirt'), 'Product', 42);

        self::assertSame(42, $payload['productId']);
        self::assertSame('TSH-0001', $payload['sku']);
        self::assertIsString($payload['occurredAt']);
    }

    public function testRehydratesAnEventWithoutPhpSerialization(): void
    {
        $codec = new OutboxEventCodec();
        $event = $codec->decode(ProductCreated::class, [
            'productId' => 42,
            'sku' => 'TSH-0001',
            'name' => 'T-Shirt',
            'occurredAt' => '2026-08-22T12:00:00+00:00',
        ]);

        self::assertInstanceOf(ProductCreated::class, $event);
        self::assertSame(42, $event->productId);
        self::assertSame('TSH-0001', $event->sku);
    }

    public function testDecodeRestoresTheOriginalOccurredAtInsteadOfNow(): void
    {
        // Regression test: decode() used to go through the concrete event's real
        // constructor, which always calls DomainEvent's own — always setting
        // occurredAt to the current time — silently discarding the value encode()
        // had put in the payload. A retried event (backoff up to 300s) or one
        // rehydrated well after it was originally raised would then report the
        // wrong occurrence time to anything reading $event->occurredAt.
        $codec = new OutboxEventCodec();
        $event = $codec->decode(ProductCreated::class, [
            'productId' => 42,
            'sku' => 'TSH-0001',
            'name' => 'T-Shirt',
            'occurredAt' => '2026-08-22T12:00:00+00:00',
        ]);

        self::assertSame('2026-08-22T12:00:00+00:00', $event->occurredAt->format(DateTimeInterface::ATOM));
    }

    public function testEncodeThenDecodeRoundTripsOccurredAtExactly(): void
    {
        $codec = new OutboxEventCodec();
        $original = new ProductCreated(42, 'TSH-0001', 'T-Shirt');

        $decoded = $codec->decode(ProductCreated::class, $codec->encode($original));

        self::assertSame(
            $original->occurredAt->format(DateTimeInterface::ATOM),
            $decoded->occurredAt->format(DateTimeInterface::ATOM),
        );
    }

    public function testDecodeRejectsAPayloadMissingOccurredAt(): void
    {
        $codec = new OutboxEventCodec();

        $this->expectException(RuntimeException::class);

        $codec->decode(ProductCreated::class, [
            'productId' => 42,
            'sku' => 'TSH-0001',
            'name' => 'T-Shirt',
        ]);
    }
}
